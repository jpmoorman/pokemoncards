// Lists every big static file the app ships (everything under models/, vendor/ and data/) with
// its size and SHA-256 in js/assets.js. The app and its service worker (sw.js) read that list:
// the service worker downloads these files in the background, keeps them for good (their names
// carry a version, so a file never changes once published), checks each download against its
// size and hash, and deletes saved files that are no longer listed.
//
//   node tools/assets.mjs           rewrite js/assets.js (after adding, replacing or removing a file)
//   node tools/assets.mjs --check   exit 1 if js/assets.js is out of date (tests/assets.test.mjs runs this)
//
// A new version of a file goes in a new folder or under a new name (models/ppocr-v6tiny-2/,
// data/details-<hash>.json): never change a published file in place, phones that have it
// would keep the old copy. Files under a LAZY prefix are listed but only downloaded when the
// app asks for them (for big optional models).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DIRS = ['models', 'vendor', 'data'];
const LAZY = []; // e.g. 'models/mobilenet-1/'
const OUT = path.join(root, 'js/assets.js');
const SKIP = /(^|\/)(\.|README|LICENSE|NOTICE)/i; // notes kept next to the files aren't downloaded by the app

/** Every shipped file: [{ path: 'data/details-….json', bytes, integrity: 'sha256-…', lazy? }], sorted by path. */
export function listAssets(dir = root) {
  const out = [];
  const walk = (rel) => {
    const abs = path.join(dir, rel);
    if (!fs.existsSync(abs)) return;
    for (const name of fs.readdirSync(abs).sort()) {
      const p = `${rel}/${name}`;
      if (fs.statSync(path.join(dir, p)).isDirectory()) walk(p);
      else if (!SKIP.test(p.slice(p.indexOf('/') + 1))) {
        const buf = fs.readFileSync(path.join(dir, p));
        out.push({
          path: p,
          bytes: buf.length,
          integrity: `sha256-${crypto.createHash('sha256').update(buf).digest('base64')}`,
          ...(LAZY.some((l) => p.startsWith(l)) && { lazy: true }),
        });
      }
    }
  };
  for (const d of DIRS) walk(d);
  return out.sort((a, b) => (a.path < b.path ? -1 : 1));
}

/** The text of js/assets.js for a list from listAssets. */
export function renderAssets(list) {
  const lines = list.map((a) => `  ${JSON.stringify(a.path)}: ${JSON.stringify({ bytes: a.bytes, integrity: a.integrity, ...(a.lazy && { lazy: true }) })}`);
  // The object is plain JSON: sw.js reads it from its saved copy of this file.
  return `// Generated by tools/assets.mjs: don't edit by hand. Run \`node tools/assets.mjs\` after adding,
// replacing or removing a file under models/, vendor/ or data/.
// Every big file the app ships: path -> { bytes, integrity (SHA-256, in the form fetch()'s
// integrity option takes), lazy (downloaded only when asked for) }. sw.js keeps exactly these.
export const ASSETS = {
${lines.join(',\n')}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const list = listAssets();
  const text = renderAssets(list);
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error('js/assets.js is out of date: run `node tools/assets.mjs`');
      process.exit(1);
    }
    console.log(`js/assets.js is up to date (${list.length} files)`);
  } else {
    fs.writeFileSync(OUT, text);
    for (const a of list) a.gzip = zlib.gzipSync(fs.readFileSync(path.join(root, a.path)), { level: 9 }).length;
    const mb = (n) => `${(n / 1e6).toFixed(2)} MB`;
    for (const a of list) console.log(`${a.path.padEnd(56)} ${mb(a.bytes).padStart(9)}  gzip ${mb(a.gzip).padStart(8)}${a.lazy ? '  (lazy)' : ''}`);
    const sum = (k) => list.reduce((s, a) => s + a[k], 0);
    console.log(`${list.length} files, ${mb(sum('bytes'))} (about ${mb(sum('gzip'))} to download with gzip) -> js/assets.js`);
  }
}
